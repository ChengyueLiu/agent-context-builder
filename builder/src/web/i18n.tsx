const DICTS: Record<Lang, Dict> = { zh, en };

const STORAGE_KEY = 'acb-ui-lang';

/** 记住的界面语言；读不到时用中文 */
export function savedLang(): Lang {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    return v === 'en' || v === 'zh' ? v : 'zh';
  } catch {
    return 'zh';
  }
}

export function saveLang(lang: Lang) {
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    // 存不了就只在这次打开时生效
  }
}

interface LangValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: Dict;
}

const LangContext = createContext<LangValue>({ lang: 'zh', setLang: () => {}, t: zh });

export function LangProvider({ lang, setLang, children }: { lang: Lang; setLang: (l: Lang) => void; children: ReactNode }) {
  return <LangContext.Provider value={{ lang, setLang, t: DICTS[lang] }}>{children}</LangContext.Provider>;
}

export const useLang = (): LangValue => useContext(LangContext);
